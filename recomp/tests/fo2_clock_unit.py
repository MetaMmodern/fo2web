def extract_clock_source() -> str:
    src = WIN32_C.read_text(encoding="utf-8")
    start = src.find(CLOCK_START)
    if start < 0:
        raise RuntimeError(f"clock start marker not found in {WIN32_C}")
    end = src.find(CLOCK_END, start)
    if end < 0:
        raise RuntimeError(f"clock end marker {CLOCK_END!r} not found in {WIN32_C}")
    clock = src[start:end]
    if "fo2_startup_qpc" not in clock or "uint64_t host_qpc(void)" not in clock:
        raise RuntimeError("extracted region does not contain the production clock helpers")
    return clock


def build_harness(tmp: pathlib.Path) -> pathlib.Path:
    clock = extract_clock_source()
    source = HARNESS.replace("/*__CLOCK_SOURCE__*/", clock)
    src = tmp / "fo2_clock_harness.c"
    src.write_text(source, encoding="utf-8")

    inc = tmp / "web"
    inc.mkdir()
    (inc / "host_abi.h").write_text(
        "#ifndef FO2_TEST_HOST_ABI_H\n"
        "#define FO2_TEST_HOST_ABI_H\n"
        "double nfsu2_now_ms(void);\n"
        "#endif\n",
        encoding="utf-8",
    )

    exe = tmp / "fo2_clock_harness"
    cc = os.environ.get("CC", "cc")
    cmd = [
        cc,
        "-std=gnu11",
        "-O0",
        "-g",
        "-Wall",
        "-Wextra",
        "-Wno-unused-parameter",
        "-DFLATOUT2",
        "-D__wasm__",
        "-I", str(tmp),
        str(src),
        "-o", str(exe),
    ]
    subprocess.run(cmd, check=True)
    return exe


class FlatOutClockTest(unittest.TestCase):
    def test_production_clock(self):
        with tempfile.TemporaryDirectory(prefix="fo2-clock-") as d:
            exe = build_harness(pathlib.Path(d))
            proc = subprocess.run(
                [str(exe)], text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE
            )
            self.assertEqual(
                proc.returncode,
                0,
                msg=textwrap.dedent(
                    f"""\
                    clock harness failed
                    stdout:
                    {proc.stdout}
                    stderr:
                    {proc.stderr}
                    """
                ),
            )
            self.assertIn("all checks passed", proc.stdout)


if __name__ == "__main__":
    unittest.main(verbosity=2)
